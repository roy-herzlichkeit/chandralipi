"""Run the pipeline over a spread of generated scenes and persist the results.

Every number it writes comes from a real execution of the real pipeline --
nothing here is mocked. What it is **not** is lunar data: no Chandrayaan-2
product drives it, the imagery is generated by :mod:`lunar_reg.eval.scenes`, and
every result is written with ``synthetic=True``.

**Writes to its own store, not the live one.** Default ``--root`` is
``data/processed/results_ch2_synthetic_backup``, kept separate from
``data/processed/results`` where real-sensor pairs live. The two were merged
once by accident -- this script regenerated its 26 pairs into the live store and
the index rebuild dropped the real ones from view (their ``.npz`` survived; see
``data/processed/demo_real/README.md``). Keeping the stores apart stops that;
``scripts/reindex_results.py`` is the tool for inspecting or merging either one.
Point the dashboard's "Results directory" box at this store to browse it.
"""

from __future__ import annotations

import argparse
import logging
import sys

from lunar_reg.eval.scenes import illumination_pair
from lunar_reg.ingest.pseudo_gt import NOMINAL_GSD_M
from lunar_reg.pipeline import BatchReport, PipelineConfig, run_batch

logger = logging.getLogger("build_demo_results")

# (label, source sun, reference sun) -- the illumination axis the problem
# statement is built around, sampled from trivial to beyond what classical
# matchers survive.
SUN_CASES = [
    ("same-sun", (285.0, 45.0), (285.0, 45.0)),
    ("mild-15deg", (285.0, 45.0), (300.0, 50.0)),
    ("hard-30deg", (285.0, 35.0), (315.0, 55.0)),
    ("extreme-180deg", (285.0, 6.0), (105.0, 62.0)),
]

# Sensor pairings we actually intend to register. IIRS is deliberately paired
# with a reference at its own scale rather than with OHRC: Makharia et al. match
# IIRS to LRO WAC at 1.25x, never to a high-resolution camera, and our own scan
# flags IIRS/OHRC at 320x as beyond any direct matcher.
SENSOR_PAIRS = [
    ("OHRC", "LRO_NAC"),
    ("TMC2", "LRO_NAC"),
    ("IIRS", "LRO_WAC"),
]

MATCHERS = ("sift", "akaze", "asift")


def build_pairs(seed_base: int = 40, size: int = 512):
    specs = []
    for sensor_index, (source_sensor, reference_sensor) in enumerate(SENSOR_PAIRS):
        for case_index, (case, source_sun, reference_sun) in enumerate(SUN_CASES):
            seed = seed_base + sensor_index * 10 + case_index
            source, reference, truth, _ = illumination_pair(
                shape=(size, size), seed=seed,
                source_sun=source_sun, reference_sun=reference_sun,
            )
            for matcher in MATCHERS:
                specs.append({
                    "source": source,
                    "reference": reference,
                    "pair_id": f"{source_sensor}-{reference_sensor}_{case}_{matcher}",
                    "source_id": f"{source_sensor}_synthetic_{seed:03d}",
                    "reference_id": f"{reference_sensor}_synthetic_{seed:03d}",
                    "source_sensor": source_sensor,
                    "reference_sensor": reference_sensor,
                    "source_sun": source_sun,
                    "reference_sun": reference_sun,
                    "synthetic": True,
                    "notes": f"generated scene, {case} illumination",
                    "_matcher": matcher,
                    "_truth": truth,
                })
    return specs


def main(argv=None) -> int:
    from lunar_reg.eval.error_budget import transform_rms_px
    from lunar_reg.results import save_results

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default="data/processed/results_ch2_synthetic_backup")
    parser.add_argument("--size", type=int, default=512)
    args = parser.parse_args(argv)

    logging.basicConfig(level=logging.WARNING, format="%(levelname)s %(message)s")

    outcomes = []
    for spec in build_pairs(size=args.size):
        matcher = spec.pop("_matcher")
        truth = spec.pop("_truth")
        config = PipelineConfig(
            matcher=matcher,
            gsd_m=NOMINAL_GSD_M.get(spec["source_sensor"]),
            extra={"case": spec["notes"]},
        )
        outcome = run_batch([spec], config=config).outcomes[0]
        if outcome.ok:
            # The truth transform is known here, so record the honest accuracy
            # alongside the self-residual RMSE. Makharia et al. report only the
            # self-residual; keeping both makes the difference visible.
            outcome.result.extra["true_rms_px"] = transform_rms_px(
                outcome.result.transform, truth, (args.size, args.size)
            )
        outcomes.append(outcome)

    combined = BatchReport(outcomes=outcomes)
    print(combined.report())
    if combined.results:
        store = save_results(combined.results, args.root)
        print()
        print(store.report())
        print()
        frame = store.frame
        columns = [
            c for c in ("pair_id", "n_inliers", "m_rmse_px", "x_true_rms_px",
                        "u_score", "c_p95_px", "x_ecc_prefilter")
            if c in frame.columns
        ]
        import pandas as pd

        with pd.option_context("display.width", 200, "display.max_rows", 100):
            print(frame[columns].to_string(index=False, float_format=lambda v: f"{v:.4f}"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
